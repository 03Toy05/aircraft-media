/** Simplified Chinese written out where mainland usage differs from a character-by-character conversion. */
export const UI_HANS_WORDS: Record<string, string> = {
  "Email": "邮箱",
  "Your email": "你的邮箱地址",
  "Email me a link": "通过邮件发送链接给我",
  "Sign in with the email you were invited with.": "请用受邀的邮箱地址登录。",
  "Privacy": "隐私",
};

/** Words swapped after converting to Simplified (Hong Kong / Taiwan usage -> mainland usage). */
const HANS_SWAPS: [string, string][] = [
  ["营运商", "运营商"], ["相片", "照片"], ["上载", "上传"], ["电邮地址", "邮箱地址"], ["电邮", "邮件"], ["讯息", "消息"],
  ["设定", "设置"], ["登入", "登录"], ["搜寻", "搜索"], ["连结", "链接"], ["储存空间", "存储空间"], ["储存", "保存"],
  ["私隐", "隐私"], ["唯读", "只读"], ["选单", "菜单"], ["批核", "批准"], ["收件匣", "收件箱"], ["装置", "设备"],
  ["底线", "下划线"], ["字眼", "措辞"], ["一次过", "一次性"], ["传送", "发送"], ["联络", "联系"],
  ["字元", "字符"], ["传到", "发到"], ["「", "“"], ["」", "”"],
];

export function toHansUi(hant: string): string {
  let s = toHans(hant);
  for (const [a, b] of HANS_SWAPS) s = s.split(a).join(b);
  return s;
}

/** One label in the screen language, with its {placeholders} filled. */
export function ui(lang: UiLang | undefined, en: string, params: UiParams = {}): string {
  let text = en;
  if (lang === "zh-Hant") text = UI_HANT[en] ?? en;
  else if (lang === "zh-Hans") text = UI_HANS_WORDS[en] ?? (UI_HANT[en] !== undefined ? toHansUi(UI_HANT[en]) : en);
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (params[k] === undefined ? m : String(params[k])));
}
